#!/usr/bin/env python3
# =============================================================================
# C# File-based app - Daily AlpacaHack
# カテゴリー: Rev | トピック: .NET | 難易度: Easy 2.5
# =============================================================================
# 【概要】
# 配布ファイル chal.cs は、入力された文字列が「正しいフラグ」かどうかを判定する
# C# プログラムです。判定の中身は次の 3 ステップだけです。
#
#   1. ソースコードに埋め込まれた Base64 文字列をデコードする
#   2. デコード結果を Brotli 形式として展開（解凍）する
#   3. 展開結果のバイト列と、入力文字列の UTF-8 バイト列が一致するか比較する
#
# つまり「正解のフラグ」は、Base64 デコード → Brotli 展開 をすれば
# そのまま取り出せます。このスクリプトは、その処理を Python で再現します。
# （Colab ノートブックと同じく、標準ライブラリ base64 と brotli パッケージを使用）
#
# 【準備】
#   pip install brotli
#   問題ページから配布ファイル (csharp-file-based-app.tar.gz) を各自ダウンロードし、
#   展開しておいてください。
#
# 【使い方】
#   python3 solve.py [chal.cs へのパス]
#   ※ パスを省略した場合は ./csharp-file-based-app/chal.cs を読み込みます。
#
# ※ フラグはこのファイルには書かれていません。実行時に計算して表示します。
# =============================================================================

import base64  # Base64 デコード用（Python 標準ライブラリ）
import re      # chal.cs から Base64 文字列を探し出すための正規表現
import sys     # コマンドライン引数の取得用

try:
    # Brotli は Python 標準ライブラリには含まれないため、外部パッケージを使います。
    # Google が公開している公式の Python バインディングです。
    import brotli
except ImportError:
    sys.exit("[!] brotli パッケージが見つかりません。`pip install brotli` を実行してください。")

# =============================================================================
# Step 0: chal.cs を読み込む
# =============================================================================
# 配布ファイルはリポジトリに含めていないため、ローカルに展開した chal.cs を読みます。
DEFAULT_PATH = "./csharp-file-based-app/chal.cs"
chal_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_PATH

try:
    with open(chal_path, encoding="utf-8") as f:
        source = f.read()
except FileNotFoundError:
    sys.exit(f"[!] {chal_path} が見つかりません。配布ファイルを展開し、パスを引数で指定してください。")

# =============================================================================
# Step 1: 埋め込まれた Base64 文字列を取り出す
# =============================================================================
# chal.cs の IsCorrect() 関数には、次のような 1 行があります。
#
#   ReadOnlySpan<byte> encoded = "...."u8;
#
# 末尾の u8 は C# 11 で追加された「UTF-8 文字列リテラル」の印で、
# 文字列を UTF-8 のバイト列 (ReadOnlySpan<byte>) として扱うという意味です。
# 中身は Base64 文字列なので、ダブルクォートの中だけを正規表現で抜き出します。
m = re.search(r'encoded\s*=\s*"([A-Za-z0-9+/=]+)"u8', source)
if not m:
    sys.exit("[!] chal.cs から Base64 文字列を見つけられませんでした。")
encoded = m.group(1)
print(f"[*] Base64 文字列 : {encoded}  ({len(encoded)} 文字)")

# =============================================================================
# Step 2: Base64 デコード
# =============================================================================
# C# 側の Base64.DecodeFromUtf8(...) に相当する処理です。
# Base64 は「バイナリデータを英数字などの文字だけで表す」ための符号化方式で、
# 4 文字 → 3 バイトに戻ります（末尾の '=' は長さ調整用のパディング）。
decoded_base64 = base64.b64decode(encoded)
print(f"[*] Base64 デコード後: {len(decoded_base64)} バイト -> {decoded_base64.hex()}")

# =============================================================================
# Step 3: Brotli 展開（解凍）
# =============================================================================
# C# 側の new BrotliDecoder().Decompress(...) に相当する処理です。
# Brotli は Google が開発した可逆圧縮形式で、HTTP の Content-Encoding: br
# などで使われています。brotli.decompress() で元のバイト列に戻せます。
flag_bytes = brotli.decompress(decoded_base64)
print(f"[*] Brotli 展開後  : {len(flag_bytes)} バイト")

# =============================================================================
# Step 4: UTF-8 文字列として表示
# =============================================================================
# C# 側では、入力文字列を Encoding.UTF8.GetBytes() でバイト列に変換し、
# Step 3 の結果と SequenceEqual() で 1 バイトずつ比較しています。
# したがって Step 3 の結果を UTF-8 として読めば、それがそのまま正解の入力です。
flag = flag_bytes.decode("utf-8")
print("[+] Flag:", flag)
